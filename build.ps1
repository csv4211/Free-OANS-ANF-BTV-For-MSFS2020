# Build AMDB OANS client.
#
#   .\build.ps1              # default: auto-update ON
#   .\build.ps1 -Fsto        # flightsim.to: auto-update OFF, name has fs.to
#
# Inno Setup optional: BUILD_INNO=1
# Edit embedded.py before building.
param(
  [switch]$Fsto
)

$ErrorActionPreference = "Stop"
Set-Location $PSScriptRoot

$verLine = (Select-String -Path .\embedded.py -Pattern '^\s*CLIENT_VERSION\s*=' | Select-Object -First 1).Line
$ver = "1.0.0"
if ($verLine -match '"([^"]+)"') { $ver = $Matches[1] }
$parts = @($ver -split '\.')
while ($parts.Count -lt 4) { $parts += '0' }
$v0 = [int]$parts[0]; $v1 = [int]$parts[1]; $v2 = [int]$parts[2]; $v3 = [int]$parts[3]

$isFsto = [bool]$Fsto -or ($env:BUILD_FSTO -eq '1')
if ($isFsto) {
  $exeBase = 'AmdbOansClient-fs.to'
  $pyiName = 'AmdbOansClient_fsto'
  $zipName = "AMDB-OANS-fs.to-$ver.zip"
  $fileDesc = 'AMDB OANS Client (flightsim.to)'
  $productExtra = ' fs.to'
} else {
  $exeBase = 'AmdbOansClient'
  $pyiName = 'AmdbOansClient'
  $zipName = "AMDB-OANS-$ver.zip"
  $fileDesc = 'AMDB OANS Client'
  $productExtra = ''
}

# channel.py is baked into the EXE — write channel flags, restore after build
$channelPath = Join-Path $PSScriptRoot 'channel.py'
$channelBackup = Get-Content -Raw -Path $channelPath
if ($isFsto) {
  $channelBody = @"
"""Build channel flags. Generated by build.ps1 — do not edit by hand for releases."""

from __future__ import annotations

BUILD_CHANNEL = "fsto"
AUTO_UPDATE = False
CHANNEL_LABEL = "fs.to"
"@
} else {
  $channelBody = @"
"""Build channel flags. Generated by build.ps1 — do not edit by hand for releases."""

from __future__ import annotations

BUILD_CHANNEL = "default"
AUTO_UPDATE = True
CHANNEL_LABEL = ""
"@
}
[System.IO.File]::WriteAllText($channelPath, $channelBody.TrimStart() + "`n", [System.Text.UTF8Encoding]::new($false))

function Write-VersionInfo([string]$OutPath, [string]$FileDescription, [string]$InternalName, [string]$OriginalFilename) {
  $vi = @"
# UTF-8
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=($v0, $v1, $v2, $v3),
    prodvers=($v0, $v1, $v2, $v3),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u'040904B0',
          [
            StringStruct(u'CompanyName', u'Free OANS AMDB'),
            StringStruct(u'FileDescription', u'$FileDescription'),
            StringStruct(u'FileVersion', u'$ver'),
            StringStruct(u'InternalName', u'$InternalName'),
            StringStruct(u'LegalCopyright', u'Copyright (c) Free OANS AMDB'),
            StringStruct(u'OriginalFilename', u'$OriginalFilename'),
            StringStruct(u'ProductName', u'AMDB OANS$productExtra'),
            StringStruct(u'ProductVersion', u'$ver'),
          ]
        )
      ]
    ),
    VarFileInfo([VarStruct(u'Translation', [1033, 1200])])
  ]
)
"@
  [System.IO.File]::WriteAllText($OutPath, $vi, [System.Text.UTF8Encoding]::new($false))
}

try {
  Write-VersionInfo (Join-Path $PSScriptRoot 'version_info.txt') $fileDesc $exeBase "$exeBase.exe"

  if (-not $isFsto) {
    $issPath = Join-Path $PSScriptRoot 'installer.iss'
    if (Test-Path $issPath) {
      $iss = [System.IO.File]::ReadAllText($issPath)
      $iss = [regex]::Replace($iss, '#define MyAppVersion "[\d.]+"', "#define MyAppVersion `"$ver`"")
      [System.IO.File]::WriteAllText($issPath, $iss, [System.Text.UTF8Encoding]::new($false))
    }
  }

  python -m pip install -q pyinstaller SimConnect cryptography
  if ($LASTEXITCODE -ne 0) { throw "pip install failed" }

  function Append-DeviceSlot([string]$ExePath) {
    $prefix = "AMDB_DEVSEC_SLOT_v1="
    $slot = $prefix + ("0" * 64)
    $bytes = [System.IO.File]::ReadAllBytes($ExePath)
    $ascii = [System.Text.Encoding]::ASCII
    $prefBytes = $ascii.GetBytes($prefix)
    $found = $false
    for ($i = $bytes.Length - $prefBytes.Length; $i -ge 0; $i--) {
      $ok = $true
      for ($j = 0; $j -lt $prefBytes.Length; $j++) {
        if ($bytes[$i + $j] -ne $prefBytes[$j]) { $ok = $false; break }
      }
      if ($ok) { $found = $true; break }
    }
    if (-not $found) {
      $tail = $ascii.GetBytes($slot)
      $out = New-Object byte[] ($bytes.Length + $tail.Length)
      [Array]::Copy($bytes, 0, $out, 0, $bytes.Length)
      [Array]::Copy($tail, 0, $out, $bytes.Length, $tail.Length)
      [System.IO.File]::WriteAllBytes($ExePath, $out)
      Write-Host "Appended device slot trailer to $(Split-Path $ExePath -Leaf)"
    }
  }

  $pyiArgs = @(
    '--noconfirm', '--clean',
    '--name', $pyiName,
    '--windowed', '--onefile',
    '--version-file', 'version_info.txt',
    '--paths', '.',
    '--add-data', 'web;web',
    '--hidden-import', 'SimConnect',
    '--hidden-import', 'cryptography',
    '--hidden-import', 'channel',
    '--collect-all', 'SimConnect'
  )
  if ($isFsto) {
    $pyiArgs += @('--exclude-module', 'updater', '--exclude-module', 'run_updater', '--exclude-module', 'helperutil')
  }
  $pyiArgs += '.\run_client.py'

  Write-Host "Building channel=$(if ($isFsto) { 'fsto' } else { 'default' }) name=$exeBase"
  python -m PyInstaller @pyiArgs
  if ($LASTEXITCODE -ne 0) { throw "PyInstaller client failed" }

  $built = Join-Path $PSScriptRoot "dist\$pyiName.exe"
  if (-not (Test-Path $built)) { throw "EXE not found: $built" }

  $exe = Join-Path $PSScriptRoot "dist\$exeBase.exe"
  if ($built -ne $exe) {
    if (Test-Path $exe) { Remove-Item $exe -Force }
    Move-Item $built $exe
  }
  Append-DeviceSlot $exe

  $hash = (Get-FileHash -Algorithm SHA256 $exe).Hash.ToLower()
  Write-Host "Built: $exe"
  Write-Host "STOCK_EXE_HASH=$hash"
  if ($isFsto) {
    Write-Host "Paste into server/embedded.py as STOCK_EXE_HASH_FSTO"
  } else {
    Write-Host "Paste into server/embedded.py as STOCK_EXE_HASH"
  }
  Write-Host "VERSION=$ver"

  $zipPath = Join-Path $PSScriptRoot "dist\$zipName"
  $stage = Join-Path $PSScriptRoot "dist\_zip_stage"
  if (Test-Path $stage) { Remove-Item $stage -Recurse -Force }
  New-Item -ItemType Directory -Path $stage | Out-Null
  Copy-Item $exe (Join-Path $stage "$exeBase.exe")
  $readmeLines = @(
    "AMDB OANS $ver$(if ($isFsto) { ' [fs.to]' } else { '' })",
    "",
    "1. Unpack this ZIP to any folder.",
    "2. Run $exeBase.exe"
  )
  if ($isFsto) {
    $readmeLines += @(
      "",
      "This flightsim.to build has no auto-update.",
      "Get new versions from flightsim.to."
    )
  } else {
    $readmeLines += @(
      "",
      "Updates and unregister are built into the same EXE."
    )
  }
  $readmeLines += @("", "Do not upload builds to VirusTotal / Hybrid Analysis.")
  [System.IO.File]::WriteAllText(
    (Join-Path $stage 'README.txt'),
    ($readmeLines -join "`r`n"),
    [System.Text.UTF8Encoding]::new($false)
  )
  if (Test-Path $zipPath) { Remove-Item $zipPath -Force }
  Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $zipPath -Force
  Remove-Item $stage -Recurse -Force
  Write-Host "ZIP: $zipPath"

  if (-not $isFsto -and $env:BUILD_INNO -eq '1') {
    $pf86 = ${env:ProgramFiles(x86)}
    $candidates = @(
      (Join-Path $env:LocalAppData 'Programs\Inno Setup 6\ISCC.exe'),
      (Join-Path $env:ProgramFiles 'Inno Setup 6\ISCC.exe')
    )
    if ($pf86) { $candidates += (Join-Path $pf86 'Inno Setup 6\ISCC.exe') }
    $iscc = $candidates | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
    if ($iscc) {
      Write-Host "Compiling installer with: $iscc"
      & $iscc .\installer.iss
      if ($LASTEXITCODE -ne 0) { throw "Inno Setup failed [exit $LASTEXITCODE]" }
      $setup = Join-Path $PSScriptRoot "dist\AMDB-OANS-Setup-$ver.exe"
      if (-not (Test-Path $setup)) { throw "Installer not created: $setup" }
      Write-Host "Installer: $setup"
    } else {
      Write-Host 'BUILD_INNO=1 but Inno Setup not found - skipped.'
    }
  }

  Write-Host 'Next:'
  if ($isFsto) {
    Write-Host "- Set STOCK_EXE_HASH_FSTO in server/embedded.py"
    Write-Host "- Set REQUIRED_CLIENT_VERSION = $ver if this is the required version"
    Write-Host "- Publish dist\$zipName on flightsim.to"
  } else {
    Write-Host '- Paste STOCK_EXE_HASH into server/embedded.py'
    Write-Host "- Set REQUIRED_CLIENT_VERSION = $ver"
    Write-Host "- Copy EXE/ZIP to server/updates/"
    Write-Host "- Publish dist\$zipName"
  }
  Write-Host '- Restart server or POST /admin/reload'
}
finally {
  [System.IO.File]::WriteAllText($channelPath, $channelBackup, [System.Text.UTF8Encoding]::new($false))
}
